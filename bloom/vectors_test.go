// TestHashVectors checks the frozen C-generated vectors against both
// hash ports — the bit-for-bit compatibility contract for merging and
// serializing filters across versions.
func TestHashVectors(t *testing.T) {
	for i, v := range hashVectors {
		if got := murmur2([]byte(v.in)); got != v.murmur {
			t.Errorf("vector %d (len %d): murmur2 = %d, want %d", i, len(v.in), got, v.murmur)
		}
		if got := superFastHash([]byte(v.in)); got != v.superFast {
			t.Errorf("vector %d (len %d): superFastHash = %d, want %d", i, len(v.in), got, v.superFast)
		}
	}
}
